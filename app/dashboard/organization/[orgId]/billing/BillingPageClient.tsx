const invoicesListResponseSchema = z.object({
  data: z.array(orgInvoiceSchema).default([]),
});

const invoicePayResponseSchema = z.object({
  razorpayOrderId: z.string().startsWith("order_"),
  keyId: z.string().min(1),
  amountPaise: z.number().int().positive(),
  currency: z.string().length(3),
  invoice: z.object({
    id: z.string(),
    invoiceNumber: z.string(),
    status: z.string(),
  }),
});
type InvoicePayResponse = z.infer<typeof invoicePayResponseSchema>;

// The per-invoice GET endpoint returns the full invoice + relations,
// but for the post-checkout poll we only care about `status`. Zod
// strips unknown fields by default so this narrow schema accepts the
// full payload and just lifts the one field we need.
const invoiceStatusPollSchema = z.object({
  invoice: z.object({
    status: z.enum(["DRAFT", "ISSUED", "PAID", "OVERDUE", "VOID", "CANCELLED"]),
  }),
});

// Same poll budget as the wallet flow (see credits/page.tsx) — 20s
// total, then we fall back to "awaiting confirmation" so the UI never
// stalls if Razorpay's webhook is slow.
const INVOICE_POLL_INTERVAL_MS = 1000;
const INVOICE_POLL_MAX_ATTEMPTS = 20;

// Discriminated union for the post-checkout flow:
//   - "confirmed": webhook landed within the poll budget; row is PAID.
//   - "pending":   capture succeeded but the webhook is slow.
//   - "not_paid":  popup dismissed or `payment.failed` fired (already
//      toasted); the success handler stays silent.
type InvoicePayMutationResult =
  | { result: InvoicePayResponse; outcome: "confirmed" }
  | { result: InvoicePayResponse; outcome: "pending" }
  | { result: InvoicePayResponse; outcome: "not_paid" };

async function fetchBilling(orgId: string): Promise<BillingSummary> {
  const res = await fetch(`/api/organizations/${orgId}/billing`);
  return parseJsonResponse(
    res,
    billingSummarySchema,
    "Failed to load billing summary",
  );
}

async function fetchInvoices(orgId: string) {
  const res = await fetch(
    `/api/organizations/${orgId}/billing-account/invoices?perPage=50`,
  );
  const parsed = await parseJsonResponse(
    res,
    invoicesListResponseSchema,
    "Failed to load invoices",
  );
  return { invoices: parsed.data };
}

async function generateInvoice(orgId: string) {
  const res = await fetch(
    `/api/organizations/${orgId}/billing/generate-invoice`,
    { method: "POST" },
  );
  const body = await res.json().catch(() => null);
  if (!res.ok)
    throw new Error(errorMessageFromBody(body, "Failed to generate invoice"));
  return body;
}

async function payInvoice(
  orgId: string,
  invoiceId: string,
): Promise<InvoicePayResponse> {
  const res = await fetch(
    `/api/organizations/${orgId}/billing-account/invoices/${invoiceId}/pay`,
    { method: "POST" },
  );
  return parseJsonResponse(
    res,
    invoicePayResponseSchema,
    "Failed to initiate payment",
  );
}

async function fetchInvoiceStatus(
  orgId: string,
  invoiceId: string,
): Promise<
  "DRAFT" | "ISSUED" | "PAID" | "OVERDUE" | "VOID" | "CANCELLED" | null
> {
  const res = await fetch(
    `/api/organizations/${orgId}/billing-account/invoices/${invoiceId}`,
  );
  if (!res.ok) return null;
  // Status poll runs in a tight loop; tolerate a transient
  // contract-drift parse failure rather than throwing the loop —
  // worst case we keep polling until the budget elapses.
  const parsed = invoiceStatusPollSchema.safeParse(await res.json());
  return parsed.success ? parsed.data.invoice.status : null;
}

/**
 * Poll the invoice endpoint until the webhook flips `status` to
 * `PAID` or the budget elapses. Returns `true` on confirmation,
 * `false` on timeout. The webhook handler (`handleOrgPaymentSuccess`)
 * is the source of truth — this exists purely so the UI doesn't lie
 * about state for ~5–20s after a successful capture.
 */
async function pollInvoiceUntilPaid(
  orgId: string,
  invoiceId: string,
): Promise<boolean> {
  for (let attempt = 0; attempt < INVOICE_POLL_MAX_ATTEMPTS; attempt++) {
    const status = await fetchInvoiceStatus(orgId, invoiceId);
    if (status === "PAID") return true;
    await new Promise((r) => setTimeout(r, INVOICE_POLL_INTERVAL_MS));
  }
  return false;
}

// FDE: whole days an OVERDUE invoice is past its dueDate (falling back to
// createdAt when dueDate is null). Ceiled so a freshly-flipped row reads
// "1 day late" — never "0 days late"; 0 only when not actually past due.
function daysLate(dueDate: string | null, createdAt: string): number {
  const ref = new Date(dueDate ?? createdAt).getTime();
  const diffMs = Date.now() - ref;
  if (diffMs <= 0) return 0;
  return Math.ceil(diffMs / (24 * 60 * 60 * 1000));
}

